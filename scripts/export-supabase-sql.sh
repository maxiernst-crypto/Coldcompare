#!/usr/bin/env bash
# Builds db/supabase-setup.sql: the full schema plus all seeded content (no users, clicks or logs),
# so a hosted database can be set up by pasting one file into the Supabase SQL editor.
# Usage: DATABASE_URL=postgres://… scripts/export-supabase-sql.sh
set -euo pipefail
out=db/supabase-setup.sql
{
  echo "-- ColdCompare: schema + initial content. Paste into Supabase → SQL Editor → Run (on an EMPTY database)."
  echo "-- Generated by scripts/export-supabase-sql.sh — do not edit by hand."
  echo "BEGIN;"
  for f in db/migrations/*.sql; do cat "$f"; echo; done
  echo "CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());"
  for f in db/migrations/*.sql; do echo "INSERT INTO schema_migrations (name) VALUES ('$(basename "$f")');"; done
  pg_dump "$DATABASE_URL" --data-only --inserts --no-owner --no-privileges \
    -t authors -t manufacturers -t products -t affiliate_links -t articles -t settings \
    | grep -vE '^(SET |SELECT pg_catalog|--|\\(un)?restrict |$)'
  echo "COMMIT;"
} > "$out"
echo "wrote $out ($(wc -c < "$out") bytes)"
